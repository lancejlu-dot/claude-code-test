/**
 * Generates supabase/seed.sql from src/lib/demo/data.ts.
 * Run: npm run gen:seed
 * Timestamps are emitted relative to the day the seed runs, so demo events stay upcoming.
 * FICTIONAL DATA — for local development and staging only.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DEMO_PASSWORD, events, members, suggestions } from "../src/lib/demo/data";
import { eventId, materializeEvents, materializeHighlights, memberId } from "../src/lib/demo/materialize";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: string[] | undefined, type = "text") => (a && a.length ? `array[${a.map(q).join(",")}]::${type}[]` : `'{}'::${type}[]`);
const json = (v: unknown) => `${q(JSON.stringify(v ?? []))}::jsonb`;
const ts = (offset: number, time: string) =>
  `((((now() at time zone 'America/Vancouver')::date + ${offset}) + time '${time}') at time zone 'America/Vancouver')`;

const out: string[] = [];
const sql = (s: string) => out.push(s.trim() + "\n");

sql(`-- =============================================================================
-- DEMO SEED — FICTIONAL people and activities for local development / staging.
-- Generated by scripts/generate-seed.ts. DO NOT run against production.
-- Demo login password for every account: ${DEMO_PASSWORD}
-- =============================================================================
set session_replication_role = default;
update public.site_settings set value = 'false' where key = 'require_member_approval';`);

// ---- Users (the auth trigger creates profiles + private rows) ----
for (const m of members) {
  const meta = {
    first_name: m.first, last_name: m.last, phone: m.phone, intro: m.intro,
    emergency_contact_name: `${m.key === "maya" ? "Wei" : "Alex"} ${m.last}`, emergency_contact_phone: m.phone.replace("555-01", "555-02"),
    emergency_contact_relationship: "Family", age_confirmed: true, guidelines_accepted: true, privacy_accepted: true,
    terms_accepted: true, photo_consent: m.photo_consent ?? true,
  };
  sql(`insert into auth.users (id, email, raw_user_meta_data, created_at) values (${q(memberId(m.key))}, ${q(m.email)}, ${json(meta)}, now() - interval '${m.joinedDaysAgo} days');`);
}

sql(`-- Supabase Auth columns (only present on a real Supabase database)
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema = 'auth' and table_name = 'users' and column_name = 'encrypted_password') then
    update auth.users set
      instance_id = '00000000-0000-0000-0000-000000000000', aud = 'authenticated', role = 'authenticated',
      encrypted_password = crypt(${q(DEMO_PASSWORD)}, gen_salt('bf')), email_confirmed_at = now(),
      raw_app_meta_data = '{"provider":"email","providers":["email"]}', updated_at = now(),
      confirmation_token = '', recovery_token = '', email_change_token_new = '', email_change = ''
    where id::text like '10000000-0000-4000-8000-%';
    insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
    select gen_random_uuid(), u.id, u.id::text, jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true),
           'email', now(), now(), now()
    from auth.users u where u.id::text like '10000000-0000-4000-8000-%'
    on conflict do nothing;
  end if;
end $$;`);

for (const m of members) {
  const id = q(memberId(m.key));
  sql(`update public.profiles set interests = ${arr(m.interests)}, city = ${q(m.city)},
    home_region_id = (select id from public.regions where slug = ${q(m.region)}), hiking_experience = ${q(m.experience)},
    experience_summary = ${q(m.experience_summary ?? null)}, skills_certifications = ${arr(m.skills)}, languages = ${arr(m.languages ?? ["English"])},
    has_vehicle = ${q(m.has_vehicle ?? false)}, willing_to_carpool = ${q(m.carpool ?? false)}, weekend_availability = array['saturday','sunday'],
    status = ${q(m.status ?? "active")}, created_at = now() - interval '${m.joinedDaysAgo} days' where id = ${id};`);
  for (const r of m.roles ?? []) sql(`insert into public.staff_roles (user_id, role) values (${id}, ${q(r)});`);
  for (const b of m.badges ?? []) sql(`insert into public.member_badges (user_id, badge_id) select ${id}, id from public.badges where slug = ${q(b)};`);
}

// ---- Events ----
const { apps } = materializeEvents();
const startExpr = new Map<string, string>();
for (const e of events) {
  const s = ts(e.dayOffset, e.start);
  startExpr.set(e.key, s);
  const before = (h?: number) => (h == null ? "null" : `${s} - interval '${h} hours'`);
  sql(`insert into public.events (id, slug, title, category_id, region_id, status, featured, cover_image_url, summary, description,
    starts_at, ends_at, general_location, distance_km, elevation_gain_m, duration_minutes, difficulty, group_pace, required_experience,
    experience_notes, fitness_expectations, required_equipment, recommended_equipment, food_water, transportation, weather_considerations,
    safety_information, max_participants, reserved_spots, registration_opens_at, registration_deadline, cancellation_deadline,
    registration_open, waitlist_mode, price_cents, deposit_cents, payment_methods, cancellation_policy, external_links, custom_sections,
    application_questions, hidden_fields, restrict_logistics, status_note, weather_cancellation, published_at, cancelled_at, created_by)
  values (${q(eventId(e.key))}, ${q(e.slug)}, ${q(e.title)}, (select id from public.activity_categories where slug = ${q(e.category)}),
    (select id from public.regions where slug = ${q(e.region)}), ${q(e.status)}, ${q(e.featured ?? false)}, ${q(e.cover)}, ${q(e.summary)}, ${q(e.description)},
    ${s}, ${ts(e.endDayOffset ?? e.dayOffset, e.end)}, ${q(e.general_location)}, ${q(e.distance_km ?? null)}, ${q(e.elevation_gain_m ?? null)},
    ${q(e.duration_minutes ?? null)}, ${q(e.difficulty)}, ${q(e.group_pace ?? null)}, ${q(e.required_experience)}, ${q(e.experience_notes ?? null)},
    ${q(e.fitness_expectations ?? null)}, ${arr(e.required_equipment)}, ${arr(e.recommended_equipment)}, ${q(e.food_water ?? null)},
    ${q(e.transportation ?? null)}, ${q(e.weather_considerations ?? null)}, ${q(e.safety_information ?? null)}, ${e.max_participants},
    ${e.reserved_spots ?? 0}, ${e.registration_opens_offset_days != null ? ts(e.registration_opens_offset_days, "09:00") : "null"},
    ${before(e.registration_deadline_offset_hours)}, ${before(e.cancellation_hours ?? 48)},
    ${q(e.status === "published" || e.status === "postponed")}, ${q(e.waitlist_mode ?? "manual")}, ${e.price_cents ?? 0}, ${e.deposit_cents ?? 0},
    ${arr(e.payment_methods ?? ["none"], "public.payment_method")}, ${q(e.cancellation_policy ?? null)}, ${json(e.external_links)},
    ${json(e.custom_sections)}, ${json(e.questions)}, ${arr(e.hidden_fields)}, ${q(e.restrict_logistics ?? true)}, ${q(e.status_note ?? null)},
    ${q(e.weather_cancellation ?? false)}, ${e.status === "draft" ? "null" : `${s} - interval '21 days'`},
    ${e.status === "cancelled" ? "now() - interval '1 day'" : "null"}, ${q(memberId("maya"))});`);
  const p = e.private;
  sql(`insert into public.event_private_details (event_id, meeting_location, meeting_location_url, meeting_time_note, parking_information, carpool_details, additional_instructions)
    values (${q(eventId(e.key))}, ${q(p.meeting_location)}, ${q(p.meeting_location_url ?? null)}, ${q(p.meeting_time_note ?? null)},
    ${q(p.parking_information ?? null)}, ${q(p.carpool_details ?? null)}, ${q(p.additional_instructions ?? null)});`);
  e.organizers.forEach((o, i) => sql(`insert into public.event_organizers (event_id, user_id, is_lead) values (${q(eventId(e.key))}, ${q(memberId(o))}, ${i === 0});`));
  for (const w of e.waivers ?? []) sql(`insert into public.event_waivers (event_id, template_id) values (${q(eventId(e.key))}, ${q(w)});`);
}

// ---- Applications, signatures, payments ----
const ev = new Map(events.map((e) => [e.key, e]));
const GENERAL = "00000000-0000-4000-b000-000000000001";
let cashToggle = 0;
for (const a of apps) {
  const e = ev.get(a.event_key)!;
  const m = members.find((x) => x.key === a.member_key)!;
  const s = startExpr.get(a.event_key)!;
  const status = a.status;
  sql(`insert into public.applications (id, event_id, user_id, status, answers, equipment_confirmed, experience_statement, waitlist_position,
    attendance, attendance_recorded_at, no_show_confirmed, confirm_by, confirmed_at, decided_at, created_at, checked_in_at, departed_safely_at, payment_choice)
  values (${q(a.id)}, ${q(eventId(e.key))}, ${q(memberId(m.key))}, ${q(status)},
    ${json(Object.fromEntries((e.questions ?? []).map((qq) => [qq.id, qq.type === "yesno" ? "yes" : "Did a similar trip last season with friends."])))},
    ${arr(e.required_equipment)}, ${q(`${m.experience} — ${m.intro}`)}, ${q(a.waitlist_position)},
    ${q(a.attendance)}, ${a.attendance ? `${s} + interval '4 hours'` : "null"}, ${a.attendance === "unexcused_no_show"},
    ${status === "approved" ? "now() + interval '40 hours'" : "null"},
    ${status === "confirmed" || status === "attended" || status === "no_show" ? `least(now(), ${s} - interval '5 days')` : "null"},
    ${["submitted", "under_review"].includes(status) ? "null" : `least(now(), ${s} - interval '7 days')`},
    least(now() - interval '1 hour', ${s} - interval '10 days'),
    ${status === "attended" ? s : "null"}, ${status === "attended" ? `${s} + interval '4 hours'` : "null"},
    ${status === "confirmed" || status === "attended" ? q((e.price_cents ?? 0) > 0 ? "online" : "none") : "null"});`);

  if (["confirmed", "attended", "no_show"].includes(status)) {
    for (const t of [GENERAL, ...(e.waivers ?? [])]) {
      sql(`insert into public.waiver_signatures (user_id, template_id, version_id, version, event_id, application_id, signature_name, signer_display, body_sha256, signed_at)
        select ${q(memberId(m.key))}, ${q(t)}, v.id, v.version, ${q(t === GENERAL ? null : eventId(e.key))}, ${q(t === GENERAL ? null : a.id)},
               ${q(`${m.first} ${m.last}`)}, ${q(`${m.first} ${m.last}`)}, encode(digest(v.body, 'sha256'), 'hex'), least(now(), ${s} - interval '6 days')
        from public.waiver_versions v where v.template_id = ${q(t)} and v.version = 1
          and not exists (select 1 from public.waiver_signatures x where x.user_id = ${q(memberId(m.key))} and x.template_id = ${q(t)});`);
    }
    if ((e.price_cents ?? 0) > 0) {
      const cash = (e.payment_methods ?? []).includes("cash") && cashToggle++ % 3 === 0 && status === "confirmed";
      sql(`insert into public.payments (application_id, event_id, user_id, kind, method, status, amount_cents, currency, receipt_number, paid_at, stripe_checkout_session_id, notes)
        values (${q(a.id)}, ${q(eventId(e.key))}, ${q(memberId(m.key))}, 'fee', ${q(cash ? "cash" : "online")}, ${q(cash ? "pending" : "paid")}, ${e.price_cents},
        'CAD', ${cash ? "null" : "public.next_receipt_number()"}, ${cash ? "null" : `least(now(), ${s} - interval '5 days')`},
        ${cash ? "null" : q(`cs_demo_${a.id.slice(-8)}`)}, ${q(cash ? "To be paid in cash (demo)" : "DEMO — not a real Stripe payment")});`);
      if (cash) sql(`update public.applications set payment_choice = 'cash' where id = ${q(a.id)};`);
    }
  }
}

// ---- Restricted member: confirmed no-show + appeal ----
sql(`update public.profiles set status = 'restricted', status_reason = 'Unexcused no-show: Lighthouse Park Coastal Loop', status_changed_at = now() - interval '25 days'
  where id = ${q(memberId("olivia"))};
insert into public.appeals (user_id, application_id, explanation, created_at)
  select ${q(memberId("olivia"))}, a.id, 'I am really sorry — my car broke down on the Lions Gate Bridge that morning and my phone died, so I could not cancel. I have attached nothing but can show the towing receipt if needed.', now() - interval '3 days'
  from public.applications a where a.user_id = ${q(memberId("olivia"))} and a.attendance = 'unexcused_no_show';
insert into public.admin_notes (user_id, body, author_id) values (${q(memberId("olivia"))}, 'First no-show. Previously reliable at 0 events (new member). Consider restoring with a reminder if appeal is credible.', ${q(memberId("daniel"))});
insert into public.member_warnings (user_id, message, issued_by, created_at) values (${q(memberId("ben"))}, 'Friendly reminder: please cancel at least 48 hours ahead so waitlisted members can take your place.', ${q(memberId("daniel"))}, now() - interval '50 days');`);

// ---- Highlights, suggestions ----
for (const h of materializeHighlights()) {
  sql(`insert into public.highlights (id, event_id, title, caption, image_url, consent_confirmed, published, sort_order)
    values (${q(h.id)}, ${q(h.event_id)}, ${q(h.title)}, ${q(h.caption)}, ${q(h.image_url)}, true, true, ${h.sort_order});`);
}
suggestions.forEach((s, i) => {
  const id = `50000000-0000-4000-8000-${String(i + 1).padStart(12, "0")}`;
  sql(`insert into public.suggestions (id, user_id, name, location, category_id, preferred_timing, difficulty, external_link, explanation, willing_to_help, status, converted_event_id, created_at)
    values (${q(id)}, ${q(memberId(s.by))}, ${q(s.name)}, ${q(s.location)}, (select id from public.activity_categories where slug = ${q(s.category)}),
    ${q(s.timing)}, ${q(s.difficulty)}, ${q(s.link ?? null)}, ${q(s.explanation)}, ${q(s.help)}, ${q(s.converted ? "converted" : "submitted")},
    ${s.converted ? q(eventId(s.converted)) : "null"}, now() - interval '${10 + i * 6} days');`);
  for (const v of s.votes) sql(`insert into public.suggestion_votes (suggestion_id, user_id) values (${q(id)}, ${q(memberId(v))});`);
});

// ---- Event community content ----
const dog = q(eventId("dog"));
sql(`insert into public.event_posts (event_id, author_id, body, is_announcement, pinned, created_at) values
  (${dog}, ${q(memberId("priya"))}, 'Welcome everyone! Snow report looks great — about 40 cm of fresh snow at the base. Rentals open at 8:30. See you at the Rental Shop!', true, true, now() - interval '20 hours'),
  (${dog}, ${q(memberId("jordan"))}, 'First time snowshoeing — any tips on what to wear? Do I need waterproof pants?', false, false, now() - interval '16 hours'),
  (${dog}, ${q(memberId("emma"))}, 'Waterproof or water-resistant pants are ideal, and avoid cotton. Gaiters help if you have them!', false, false, now() - interval '15 hours'),
  (${dog}, ${q(memberId("aisha"))}, 'I have two spare seats from Richmond if anyone needs a ride — posted on the carpool board.', false, false, now() - interval '10 hours');
insert into public.carpool_offers (event_id, driver_id, seats, departure_area, departure_time_note, notes)
  values (${dog}, ${q(memberId("aisha"))}, 3, 'Richmond (Brighouse Station)', 'Leaving 7:45', 'Winter tires, room for snowshoes in the trunk.');
insert into public.carpool_riders (offer_id, rider_id) select id, ${q(memberId("zoe"))} from public.carpool_offers where event_id = ${dog} and driver_id = ${q(memberId("aisha"))};
insert into public.headcounts (event_id, label, counted, expected, recorded_by, recorded_at) values
  (${q(eventId("lighthouse"))}, 'Trailhead start', 10, 11, ${q(memberId("priya"))}, ${startExpr.get("lighthouse")} + interval '10 minutes'),
  (${q(eventId("lighthouse"))}, 'Point Atkinson viewpoint', 10, 10, ${q(memberId("priya"))}, ${startExpr.get("lighthouse")} + interval '90 minutes'),
  (${q(eventId("lighthouse"))}, 'Back at cars', 10, 10, ${q(memberId("priya"))}, ${startExpr.get("lighthouse")} + interval '3 hours');
insert into public.incidents (event_id, severity, occurred_at, summary, details, actions_taken, recorded_by, resolved) values
  (${q(eventId("buntzen"))}, 'minor', ${startExpr.get("buntzen")} + interval '2 hours', 'Rolled ankle on descent', 'Participant slipped on wet roots near the North Beach junction.', 'Taped ankle, walked out slowly with an organizer. Participant drove home and reported they were fine.', ${q(memberId("sofia"))}, true);
insert into public.content_reports (reporter_id, subject_user_id, event_id, category, details, created_at) values
  (${q(memberId("chloe"))}, null, ${q(eventId("buntzen"))}, 'safety', 'A section of the trail near the north end had a fallen tree across it — might be worth checking before the next trip.', now() - interval '35 days');
insert into public.member_groups (id, name, description) values ('60000000-0000-4000-8000-000000000001', 'Winter crew', 'Members with winter / snowshoe experience');
insert into public.member_group_members (group_id, user_id) values
  ('60000000-0000-4000-8000-000000000001', ${q(memberId("emma"))}), ('60000000-0000-4000-8000-000000000001', ${q(memberId("priya"))}),
  ('60000000-0000-4000-8000-000000000001', ${q(memberId("lucas"))}), ('60000000-0000-4000-8000-000000000001', ${q(memberId("ava"))});`);

// A pending membership request (created after approval is re-enabled so the normal flow applies)
sql(`update public.profiles set status = 'pending' where id = ${q(memberId("sam"))};
insert into public.notifications (user_id, type, title, body, link) select user_id, 'membership_pending', 'New member awaiting approval', 'Sam T. has requested to join.', '/admin/members?status=pending'
  from public.staff_roles where role in ('owner','admin');
update public.site_settings set value = 'true' where key = 'require_member_approval';
-- Demo emails are never sent.
update public.email_outbox set status = 'skipped', last_error = 'Demo seed — not sent';`);

const path = resolve(__dirname, "../supabase/seed.sql");
